# Generate the workload

import random

def make_request(request_id):
  return MaintenanceRequest(request_id, "Library", "Plumbing",
                            1, request_id, "Open")

def generate_workload(seed=38):
  random.seed(seed)

  operations = []
  current_ids = list(range(1,10001))
  next_id = 10001

  for i in range(20000):
    choice = random.random()

    if choice < 0.50:
      operations.append(("push", next_id))
      current_ids.insert(0, next_id)
      next_id += 1

    elif choice < 0.90:
      if len(current_ids) > 0:
        operations.append(("removeAt", 0))
        current_ids.pop(0)
      else:
        operations.append(("findById", -1))

    else:
      if len(current_ids) > 0 and random.random() < 0.80:
        request_id = random.choice(current_ids)
      else:
        request_id = -1

      operations.append(("findById", request_id))

  return operations


# Workload Replay and Operation Check

def replay_workload(request_list, operations):

  for operation, value in operations:

    if operation == "push":
      request_list.push(make_request(value))

    elif operation == "removeAt":
      request_list.removeAt(value)

    elif operation == "findById":
      request_list.findById(value)

  return request_list.count()

# Generate the workload using seed 38

operations = generate_workload(38)

# Check the number of operations

print("Total operations:", len(operations))
print("First 5 operations:", operations[:5])

assert len(operations) == 20000


# Benchmark Timing and Results

import time
import statistics

def run_benchmark(list_type, operations):
  times = []
  final_sizes = []

  # Run this test 5 times

  for run in range(5):
    request_list = list_type()

    # Start with 10,000 maintenance requests

    for request_id in range(1, 10001):
      request_list.append(make_request(request_id))

    # Time only the 20,000 workload requests
    start_time = time.perf_counter()

    final_size = replay_workload(request_list, operations)

    end_time = time.perf_counter()

    elapsed_time = end_time - start_time
    times.append(elapsed_time)
    final_sizes.append(final_size)

    print("Run", run + 1, ":", round(elapsed_time, 4), "seconds")

  median_time = statistics.median(times)

  return median_time, final_sizes

print("Dynamic Array")
array_time, array_sizes = run_benchmark(ArrayRequestList, operations)

print()
print("Linked List")
linked_time, linked_sizes = run_benchmark(LinkedRequestList, operations)

